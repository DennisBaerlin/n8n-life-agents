#Requires -Version 5.1
# Capabilities-Catalog (Phase 4 Discoverability, WS-B7 Per-Fragment, Textkatalog Phase B je Sprache) — baut die
# nutzerseitige /help-Uebersicht. Dot-gesourct von build.ps1 (Generierung + -VerifyCatalog).
#
# PER-FRAGMENT-MODELL (WS-B7): JEDES Paket BESITZT seine Katalog-STRUKTUR im manifest.json-`catalog`-Block
# (ord, categories[{id,ord}], tail[{id,ord}]); die Engine kennt KEINE paket-spezifischen Kategorien (Open/Closed).
# TEXTE (Phase B): Titel, Beschreibung, Beispiele und Tail-Abschnitte stehen im Textkatalog des Pakets
# (<pkg>.help.<id>.title|description|ex1..3, Tail <pkg>.help.<id>.title|body; Kopf core.help.*), je Sprache der
# Core-Manifest-Liste languages.list. Ein fehlender Key in einer Sprache faellt wie zur Laufzeit auf en zurueck.
#   - Build-CatalogFragment: rendert je Paket UND Sprache ein Fragment (frontmatter-los, GENERATED-Kommentar) unter
#     packages/<pkg>/seed/capabilities_catalog/<lang>.fragment.md (Pfad per Konvention).
#   - Build-ComposedCatalog: setzt die Fragmente einer Sprache (nach Paket-`ord`) + Kopf zur getrackten
#     packages/core/seed/capabilities_catalog/<lang>.md zusammen (Kopf-Quelle des Install-Compose) und faehrt die
#     Telegram-Laengen-Assert. Der Installer komponiert zur Laufzeit nur die AKTIVEN Pakete (seed_data.sh).
# Eine Kategorie erscheint nur, wenn ein Tool des Pakets sie per _manifest.Category = <id> nutzt (forward-
# declaration erlaubt). Jedes DEUTSCHE Beispiel ist verbatim eine reale Routing-Case-Utterance (Drift-Lint);
# die Uebersetzungen tragen dieselbe Aussage.

# GENERATED-Marker je Fragment-File (Hand-Edit-Verbot sichtbar; beim Compose gestrippt, sonst Literal-Text im /help).
$script:CatalogGeneratedComment = '<!-- GENERATED by scripts/build/build.ps1 (capabilities-catalog fragment) - never hand-edit. -->'
$script:CatalogMaxExamples = 3   # max. 3 Beispiele je Kategorie (WS-5 Owner-Wahl "reich"; Verb-Klassen spannen).

# ORDINAL-Sort (kultur-unabhaengig -> stabiler Hash auf jeder Culture/CI; Review A3).
# Sort-Object waere current-culture-sensitiv -> potenzieller Hash-Drift im harten Gate.
function Sort-Ordinal {
    param([string[]]$Items)
    $a = [string[]]$Items
    [Array]::Sort($a, [System.StringComparer]::Ordinal)
    return $a
}

# --- Katalog-Sprachen = Core-Manifest languages.list (nach ord) ---
function Get-CatalogLanguages {
    param([Parameter(Mandatory)][string]$RepoRoot)
    $mf = [System.IO.File]::ReadAllText((Join-Path $RepoRoot 'packages\core\manifest.json'), (New-Object System.Text.UTF8Encoding($false))) | ConvertFrom-Json
    @(@($mf.languages.list) | Sort-Object { [int]$_.ord } | ForEach-Object { [string]$_.code })
}

# --- Text-Lookup im getrackten Katalog (Datei = Wahrheit), Kette <lang> -> en; fehlt der Key ganz -> throw ---
$script:CatalogLocaleCache = @{}
function Get-CatalogText {
    param([Parameter(Mandatory)][string]$RepoRoot, [Parameter(Mandatory)][string]$Key, [Parameter(Mandatory)][string]$Lang)
    $pkg = $Key.Split('.')[0]
    foreach ($l in @($Lang, 'en')) {
        $ck = "$pkg|$l"
        if (-not $script:CatalogLocaleCache.ContainsKey($ck)) {
            $f = Join-Path $RepoRoot "packages\$pkg\locales\$l.json"
            $script:CatalogLocaleCache[$ck] = if (Test-Path $f) { [System.IO.File]::ReadAllText($f, (New-Object System.Text.UTF8Encoding($false))) | ConvertFrom-Json } else { $null }
        }
        $obj = $script:CatalogLocaleCache[$ck]
        if ($null -ne $obj -and $null -ne $obj.PSObject.Properties[$Key]) { return [string]$obj.$Key }
    }
    throw "capabilities_catalog: Text-Key '$Key' fehlt in packages/$pkg/locales ($Lang und en)"
}
function Test-CatalogKey {
    param([Parameter(Mandatory)][string]$RepoRoot, [Parameter(Mandatory)][string]$Key)
    try { [void](Get-CatalogText $RepoRoot $Key 'en'); return $true } catch { return $false }
}

# --- Sammelt alle Case-Utterances (tasks) aus den tracked *_cases.json (Pool fuer den Example-Check) ---
function Get-CaseUtterance {
    param([Parameter(Mandatory)][string]$RepoRoot)
    $set = New-Object 'System.Collections.Generic.HashSet[string]'
    # Phase D: alle tests/agent/*/*_cases.json (lib/agent_cases.ps1, keine Paket-Liste); Pool = die Utterances
    # der ROUTING-Cases = Schluessel expected_tool ODER expected_route VORHANDEN (auch null/[] — "kein Tool"-Cases
    # tragen echte Help-Beispiele). E2E-/Infra-/Ingress-Cases ohne diese Schluessel fallen heraus.
    foreach ($cf in (Get-AgentCaseFile $RepoRoot)) {
        foreach ($c in $cf.Cases) {
            if (-not ((Test-CaseHasKey $c 'expected_tool') -or (Test-CaseHasKey $c 'expected_route'))) { continue }
            if ($c.task) { [void]$set.Add(($c.task -replace '\s+', ' ').Trim()) }
            foreach ($t in @($c.turns)) {   # Multi-Turn: Turns sind Strings (oder {task}-Objekte)
                $tt = if ($t -is [string]) { $t } elseif ($null -ne $t) { $t.task } else { $null }
                if ($tt) { [void]$set.Add(($tt -replace '\s+', ' ').Trim()) }
            }
        }
    }
    if ($set.Count -eq 0) { throw 'Get-CaseUtterance: leerer Case-Pool (Case-Dateien/Schema kaputt?).' }
    return , $set
}

# --- Findet deutsche Katalog-Beispiele (<pkg>.help.<id>.exN in de.json) ohne zugehoerigen Routing-Case ---
# Rueckgabe: Liste "<key> -> '<beispiel>'" ohne Case. Die Testbindung gilt fuer die deutsche Fassung (die
# Golden-Cases sind deutsch); en/ko sind Uebersetzungen derselben Aussage.
function Find-CatalogExamplesWithoutCase {
    param([Parameter(Mandatory)][string]$RepoRoot)
    $pool = Get-CaseUtterance -RepoRoot $RepoRoot
    $missing = @()
    foreach ($f in (Get-ChildItem (Join-Path $RepoRoot 'packages\*\locales\de.json'))) {
        $obj = [System.IO.File]::ReadAllText($f.FullName, (New-Object System.Text.UTF8Encoding($false))) | ConvertFrom-Json
        foreach ($p in $obj.PSObject.Properties) {
            if ($p.Name -notmatch '^[a-z0-9_]+\.help\.[a-z0-9_]+\.ex\d+$') { continue }
            $norm = ([string]$p.Value -replace '\s+', ' ').Trim()
            if (-not $pool.Contains($norm)) { $missing += "$($p.Name) -> '$($p.Value)'" }
        }
    }
    return $missing
}

# --- Findet Tool-Categories, die NICHT im catalog-Block des eigenen Pakets deklariert sind (WS-B7 m3) ---
# Frueher fielen solche (Tippfehler-)Categories still hinten an; jetzt harter Verify-FAIL + Cross-Paket-Leck-Schutz.
# $PkgManifests: hashtable name -> @{Category} (Tools DIESES Pakets). $DeclaredIds: string[] der catalog.categories[].id.
function Find-UndeclaredCategories {
    param([Parameter(Mandatory)]$PkgManifests, [Parameter(Mandatory)][AllowEmptyCollection()][string[]]$DeclaredIds)
    $missing = @()
    foreach ($name in (Sort-Ordinal @($PkgManifests.Keys))) {
        $cat = $PkgManifests[$name].Category
        if (-not $cat) { continue }
        if ($DeclaredIds -notcontains $cat) { $missing += "$name -> '$cat'" }
    }
    return $missing
}

# --- Fehlende Pflicht-Texte eines catalog-Blocks (Titel/Beschreibung je Kategorie, Titel/Body je Tail) ---
function Find-MissingCatalogTexts {
    param([Parameter(Mandatory)][string]$RepoRoot, [Parameter(Mandatory)][string]$Package, [Parameter(Mandatory)]$CatalogMeta)
    $missing = @()
    foreach ($c in @($CatalogMeta.categories)) {
        foreach ($s in 'title', 'description') { $k = "$Package.help.$($c.id).$s"; if (-not (Test-CatalogKey $RepoRoot $k)) { $missing += $k } }
    }
    foreach ($t in @($CatalogMeta.tail)) {
        foreach ($s in 'title', 'body') { $k = "$Package.help.$($t.id).$s"; if (-not (Test-CatalogKey $RepoRoot $k)) { $missing += $k } }
    }
    return $missing
}

# --- Rendert das Katalog-Fragment EINES Pakets in EINER Sprache (deterministisch -> stabiler Hash) ---
# $CatalogMeta: der manifest.json-`catalog`-Block (.categories[{id,ord}], .tail[{id,ord}]).
# $PkgManifests: hashtable name -> @{Category} der Tools dieses Pakets.
# Rueckgabe: Fragment-Markdown (frontmatter-los, fuehrender GENERATED-Kommentar; eof = ein '\n').
function Build-CatalogFragment {
    param(
        [Parameter(Mandatory)][string]$Package,
        [Parameter(Mandatory)]$CatalogMeta,
        [Parameter(Mandatory)]$PkgManifests,
        [Parameter(Mandatory)][string]$Lang,
        [Parameter(Mandatory)][string]$RepoRoot
    )
    $used = @{}
    foreach ($name in @($PkgManifests.Keys)) { $c = $PkgManifests[$name].Category; if ($c) { $used[[string]$c] = $true } }

    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine($script:CatalogGeneratedComment)
    [void]$sb.AppendLine('')
    # Kategorien nach ord; nur rendern, wenn ein Tool des Pakets sie nutzt. Beispiele ex1..ex3, soweit im Katalog.
    foreach ($c in (@($CatalogMeta.categories) | Sort-Object { [int]$_.ord }, { $_.id })) {
        if (-not $used.ContainsKey([string]$c.id)) { continue }
        $base = "$Package.help.$($c.id)"
        [void]$sb.AppendLine('## ' + (Get-CatalogText $RepoRoot "$base.title" $Lang))
        [void]$sb.AppendLine((Get-CatalogText $RepoRoot "$base.description" $Lang))
        for ($i = 1; $i -le $script:CatalogMaxExamples; $i++) {
            if (-not (Test-CatalogKey $RepoRoot "$base.ex$i")) { break }
            [void]$sb.AppendLine('- "' + (Get-CatalogText $RepoRoot "$base.ex$i" $Lang) + '"')
        }
        [void]$sb.AppendLine('')
    }
    # Paket-eigene tail-Sektionen (Agent-/Kommando-Capabilities, NICHT tool-derived) nach ord.
    foreach ($t in (@($CatalogMeta.tail) | Sort-Object { [int]$_.ord }, { $_.id })) {
        if (-not $t) { continue }
        $base = "$Package.help.$($t.id)"
        [void]$sb.AppendLine('## ' + (Get-CatalogText $RepoRoot "$base.title" $Lang))
        [void]$sb.AppendLine((Get-CatalogText $RepoRoot "$base.body" $Lang))
        [void]$sb.AppendLine('')
    }

    # LF-normalisiert + eof = genau ein '\n' (eof-fixer-konform: packages/*/seed/ ist NICHT vom Hook excludiert).
    return (($sb.ToString() -replace "`r`n", "`n").TrimEnd() + "`n")
}

# --- Setzt die Fragmente EINER Sprache + Kopf zur komponierten Uebersicht zusammen ---
# $Fragments: @(@{ Package; Ord; Body }) — Body = Fragment-Markdown (mit GENERATED-Kommentar).
# Paket-Reihenfolge deterministisch ueber Paket-`Ord` (NIE Verzeichnis-Glob); Laengen-Assert ueber das Ergebnis.
function Build-ComposedCatalog {
    param([Parameter(Mandatory)]$Fragments, [Parameter(Mandatory)][string]$Lang, [Parameter(Mandatory)][string]$RepoRoot)
    $sb = New-Object System.Text.StringBuilder
    [void]$sb.AppendLine('# ' + (Get-CatalogText $RepoRoot 'core.help.title' $Lang))
    [void]$sb.AppendLine('')
    [void]$sb.AppendLine((Get-CatalogText $RepoRoot 'core.help.intro' $Lang))
    [void]$sb.AppendLine('')

    foreach ($f in ($Fragments | Sort-Object { [int]$_.Ord }, { $_.Package })) {
        # GENERATED-Kommentar (1. Zeile) strippen — sonst Literal-Text im plain-text-/help-Body.
        $body = (($f.Body -replace "`r`n", "`n") -replace '(?s)^\s*<!--.*?-->\s*', '').TrimEnd()
        if ([string]::IsNullOrWhiteSpace($body)) { continue }
        [void]$sb.Append($body)
        [void]$sb.AppendLine('')
        [void]$sb.AppendLine('')
    }

    # LF-normalisiert (stabiler Hash unabhaengig von CRLF) + eof = ein '\n'.
    $md = ($sb.ToString() -replace "`r`n", "`n").TrimEnd() + "`n"

    # /help-Chunking-Invariante (WS-5): /help splittet den Text an `## `-Kategorie-Grenzen in MEHRERE Telegram-
    # Nachrichten (Code-Node `Split help` im Orchestrator) + sendet sie per-Item. Telegram-Hardfail bei 4096 -> hier
    # build-time je BLOCK + Index hart begrenzen, damit der Runtime-Greedy-Packer jeden Chunk per Konstruktion < 4096
    # haelt. KEINE Packer-Algorithmus-Duplikation: der Build sichert nur die Block-/Index-Invariante, der Runtime
    # packt. Format-Mirror: $tx + Index-Aufbau unten == der JS-Transform/Index in `Split help`
    # (packages/core/build/workflows/agent.orchestrator.ps1); die Index-Zeile ist core.help.index.
    $PackBudget = 4000   # 4096 - (n/N)-Praefix(<=16) - Marge; SPIEGELT `const PACK_BUDGET` im Split-help-Code-Node.
    $tx = { param($s) ($s -replace '(?m)^##\s*', '> ') -replace '(?m)^#\s*', '' }           # exakt der Runtime-Transform
    $parts    = $md -split '(?m)(?=^## )'                                                   # [Praeambel, Block1, Block2, ...]
    $preamble = $parts[0]
    $blocks   = @($parts | Select-Object -Skip 1)
    foreach ($blk in $blocks) {                                                            # (i) Per-Block-Cap (Header inkl., transformiert)
        $t = (& $tx $blk).TrimEnd()
        if ($t.Length -gt $PackBudget) {
            $hdr = ([regex]::Match($blk, '(?m)^##\s+(.+)$')).Groups[1].Value.Trim()
            throw "capabilities_catalog ($Lang): /help-Block '$hdr' $($t.Length) Zeichen > $PackBudget (Limit 4096). Beispiele dieser Kategorie kuerzen."
        }
    }
    $headers  = [regex]::Matches($md, '(?m)^##\s+(.+)$') | ForEach-Object { $_.Groups[1].Value.Trim() }
    $indexMsg = ((& $tx $preamble).Trim()) + "`n`n" + (Get-CatalogText $RepoRoot 'core.help.index' $Lang) + "`n" + (($headers | ForEach-Object { "$([char]0x2022) $_" }) -join "`n")
    if ($indexMsg.Length -gt $PackBudget) {                                                # (ii) Index-Cap (projizierte erste /help-Nachricht)
        throw "capabilities_catalog ($Lang): /help-Index $($indexMsg.Length) Zeichen > $PackBudget (Limit 4096). Zu viele Kategorien."
    }
    return $md
}
